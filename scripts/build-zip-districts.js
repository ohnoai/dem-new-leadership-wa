// Builds districts.js: which congressional district(s) each Washington ZIP code falls in.
//
// Source: U.S. Census Bureau 2020 ZCTA to 119th Congressional District relationship file for Washington:
//   https://www2.census.gov/geo/docs/maps-data/data/rel2020/cd-sld/tab20_cd11920_zcta520_st53.txt
// Download it, then run:  node scripts/build-zip-districts.js path/to/tab20_cd11920_zcta520_st53.txt
//
// Census ZIP Code Tabulation Areas approximate postal ZIP codes. A ZIP that crosses a district line lists every
// district it touches, largest land share first. Overlaps under 0.1% of the ZIP's land are boundary noise and dropped.
// Another state: use that state's file (st53 is Washington's FIPS code) and update the state code below.
const fs = require('node:fs');
const path = require('node:path');

const STATE = 'WA';
const source = process.argv[2];
if (!source) { console.error('Usage: node scripts/build-zip-districts.js <Census relationship file>'); process.exit(1); }

const rows = fs.readFileSync(source, 'utf8').replace(/^﻿/, '').trim().split(/\r?\n/).map(line => line.split('|'));
const header = rows.shift();
const col = name => { const i = header.indexOf(name); if (i < 0) throw new Error(`Missing column ${name}`); return i; };
const [cd, zcta, zipLand, partLand] = ['GEOID_CD119_20', 'GEOID_ZCTA5_20', 'AREALAND_ZCTA5_20', 'AREALAND_PART'].map(col);

const zips = {};
for (const r of rows) {
  if (!r[zcta]) continue;
  const share = +r[zipLand] ? +r[partLand] / +r[zipLand] : 0;
  if (share < 0.001) continue;
  (zips[r[zcta]] ||= []).push([+r[cd].slice(2), share]);
}
const out = Object.fromEntries(Object.keys(zips).sort().map(zip => [zip, zips[zip].sort((a, b) => b[1] - a[1]).map(([d]) => d)]));

const file = path.resolve(__dirname, '..', 'districts.js');
fs.writeFileSync(file, `/* Generated by scripts/build-zip-districts.js from the U.S. Census Bureau 2020 ZCTA to 119th Congressional
   District relationship file. Do not edit by hand. ZIP code -> district numbers, largest land share first. */
window.CAMPAIGN_ZIPS = { state: '${STATE}', zips: ${JSON.stringify(out)} };
`);
const split = Object.values(out).filter(d => d.length > 1).length;
console.log(`wrote ${file}: ${Object.keys(out).length} ZIP codes, ${split} cross a district line`);
